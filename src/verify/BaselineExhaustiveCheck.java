package verify;

import algorithms.HUSPSPAlgorithm;
import algorithms.HUSPULLAlgorithm;
import algorithms.USpanAlgorithm;
import common.Pattern;
import common.Sequence;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Random;
import java.util.Set;

/**
 * The static baselines against exhaustive enumeration, on the small random databases of
 * ItemRemovalCheck random (same generator, same seed, so the same databases), at the two thresholds
 * that check uses: UUT * TU, and r * UUT * TU when the ratio r is below 1.
 *
 *   java -cp build verify.BaselineExhaustiveCheck TRIALS SEED      (the paper's check: 2000 1)
 *
 * Five miners: USpan, HUSP-SP and HUSP-ULL as measured (src/algorithms), and the two variants with
 * the bound as published (USpanAsPublished, HUSPSPAsPublished, generated by
 * tools/make_published_bound_variants.py). Each comparison is a pattern set with every utility,
 * against IncUspVerifier.bruteForceHusps, which lists occurrences one by one. A pattern that the
 * enumeration lists and a miner does not is missing; one the miner lists and the enumeration does not
 * is extra.
 *
 * Also runs the five on the counterexample of the paper, one sequence
 * <(a:1)(b:1)(a:50)(g:1)(b:1)(g:1)> with unit values 1 (items 1, 2, 3), at threshold 52.
 *
 * Also runs them on a counterexample to Eq. (21) of USpan, <(a:1)(a:50 b:1)(b:1)(c:1)>, at 52.
 *
 * Exits 1 when a measured baseline differs from the enumeration anywhere, or when a published
 * bound does not miss <(1)(2)(3)> on its counterexample (the check would then be blind).
 */
public final class BaselineExhaustiveCheck {

    private BaselineExhaustiveCheck() {}

    static final String[] NAMES = {"USpan", "HUSP-SP", "HUSP-ULL", "USpan-as-published", "HUSP-SP-as-published"};
    static final boolean[] MEASURED = {true, true, true, false, false};

    static Map<String, Double> asStrings(Map<Pattern, Double> m) {
        Map<String, Double> out = new HashMap<>(m.size() * 2);
        for (Map.Entry<Pattern, Double> e : m.entrySet()) out.put(e.getKey().toIntuitiveString(), e.getValue());
        return out;
    }

    /** Each miner gets its own copy of the database, built from the same specs. */
    static Map<String, Double> mine(int k, List<String> specs, double minUtil) {
        SyntheticDb.resetIds();
        List<Sequence> db = new ArrayList<>();
        for (String sp : specs) db.add(SyntheticDb.seq(sp));
        switch (k) {
            case 0: { USpanAlgorithm a = new USpanAlgorithm(minUtil); a.run(db); return asStrings(a.largeMap); }
            case 1: { HUSPSPAlgorithm a = new HUSPSPAlgorithm(minUtil); a.run(db); return asStrings(a.largeMap); }
            case 2: { HUSPULLAlgorithm a = new HUSPULLAlgorithm(minUtil); a.run(db); return asStrings(a.largeMap); }
            case 3: { USpanAsPublished a = new USpanAsPublished(minUtil); a.run(db); return asStrings(a.largeMap); }
            case 4: { HUSPSPAsPublished a = new HUSPSPAsPublished(minUtil); a.run(db); return asStrings(a.largeMap); }
            default: throw new IllegalArgumentException("miner " + k);
        }
    }

    public static void main(String[] a) {
        if (a.length < 2) { System.out.println("usage: BaselineExhaustiveCheck TRIALS SEED"); System.exit(2); }
        int trials = Integer.parseInt(a[0]);
        long seed = Long.parseLong(a[1]);
        int m = NAMES.length;
        long[] badCmp = new long[m], missing = new long[m], extra = new long[m], utilBad = new long[m];
        double[] maxGap = new double[m];
        Set<Integer>[] badDbs = new Set[m];
        for (int k = 0; k < m; k++) badDbs[k] = new HashSet<>();
        String[] firstBad = new String[m];
        long comparisons = 0, atUut = 0, atCutoff = 0, refPatterns = 0, dbsWithPattern = 0;

        // The generator of ItemRemovalCheck random, call for call, so trial t is the same database.
        Random r = new Random(seed);
        for (int t = 0; t < trials; t++) {
            SyntheticDb.resetIds();
            double su = ItemRemovalCheck.SUS[r.nextInt(ItemRemovalCheck.SUS.length)];
            double ratio = ItemRemovalCheck.RATIOS[r.nextInt(ItemRemovalCheck.RATIOS.length)];
            int n = 8 + r.nextInt(13);
            List<String> specs = new ArrayList<>();
            List<Sequence> db = new ArrayList<>();
            for (int i = 0; i < n; i++) { String sp = ItemRemovalCheck.randSeq(r); specs.add(sp); db.add(SyntheticDb.seq(sp)); }
            double tsu = SyntheticDb.tsu(db);
            List<double[]> levels = new ArrayList<>();
            levels.add(new double[]{su, tsu * su});
            if (ratio < 1.0) levels.add(new double[]{ratio * su, tsu * (ratio * su)});
            boolean any = false;
            for (double[] lv : levels) {
                Map<String, Double> ref = IncUspVerifier.bruteForceHusps(db, lv[0]);
                comparisons++;
                if (lv[0] == su) atUut++; else atCutoff++;
                refPatterns += ref.size();
                any |= !ref.isEmpty();
                for (int k = 0; k < m; k++) {
                    Map<String, Double> got = mine(k, specs, lv[1]);
                    PatternSetDiff d = PatternSetDiff.of(ref, got);
                    if (!d.isClean()) {
                        badCmp[k]++; badDbs[k].add(t);
                        missing[k] += d.missing; extra[k] += d.extra;
                        if (d.maxUtilityGap > PatternSetDiff.UTILITY_TOLERANCE) utilBad[k]++;
                        if (d.maxUtilityGap > maxGap[k]) maxGap[k] = d.maxUtilityGap;
                        if (firstBad[k] == null) firstBad[k] = "trial " + t + " threshold-share=" + lv[0] + " " + d
                                + "\n      db: " + String.join(" ; ", specs);
                    }
                }
            }
            if (any) dbsWithPattern++;
        }
        System.out.printf("baseline-exhaustive trials=%d seed=%d comparisons=%d (at UUT %d, at the cutoff below UUT %d) "
                + "databases-with->=1-pattern=%d reference-patterns=%d%n",
                trials, seed, comparisons, atUut, atCutoff, dbsWithPattern, refPatterns);
        int bad = 0;
        for (int k = 0; k < m; k++) {
            System.out.printf("  %-21s %-9s mismatching-comparisons=%d mismatching-databases=%d missing=%d extra=%d "
                    + "comparisons-with-a-utility-gap=%d maxUtilGap=%.6f%n",
                    NAMES[k], MEASURED[k] ? "measured" : "published", badCmp[k], badDbs[k].size(), missing[k], extra[k],
                    utilBad[k], maxGap[k]);
            if (firstBad[k] != null) System.out.println("    first mismatch: " + firstBad[k]);
            if (MEASURED[k]) bad += (int) Math.min(Integer.MAX_VALUE, badCmp[k]);
        }

        // The counterexample of the paper: <(1)(2)(3)> has utility 52 (a@3, b@5, g@6).
        List<String> cx = List.of("1[1] | 2[1] | 1[50] | 3[1] | 2[1] | 3[1]");
        String target = new Pattern(1).sConcatenate(2).sConcatenate(3).toIntuitiveString();
        SyntheticDb.resetIds();
        double cxTu = SyntheticDb.tsu(List.of(SyntheticDb.seq(cx.get(0))));
        System.out.printf("counterexample <(1:1)(2:1)(1:50)(3:1)(2:1)(3:1)> TU=%.0f threshold 52, %s utility 52:%n", cxTu, target);
        boolean blind = false;
        for (int k = 0; k < m; k++) {
            Map<String, Double> got = mine(k, cx, 52.0);
            boolean has = got.containsKey(target);
            System.out.printf("  %-21s returns it: %s%n", NAMES[k], has ? "yes" : "no");
            if (MEASURED[k] && !has) bad++;
            if (NAMES[k].equals("HUSP-SP-as-published") && has) blind = true;
        }
        if (blind) { System.out.println("  the published HUSP-SP bound does not miss the pattern: the check is blind"); bad++; }

        // A counterexample to Eq. (21) of USpan, built here: t = <(a)(b)> has its pivot at b of the second
        // element (the a of that element cannot precede it in a sequence extension), so the bound is
        // u = 2 (a@1, b@2) plus the utility after it, 2; the offspring <(a)(b)(c)> has utility 52 (a:50).
        List<String> ux = List.of("1[1] | 1[50] 2[1] | 2[1] | 3[1]");
        System.out.printf("counterexample <(1:1)(1:50 2:1)(2:1)(3:1)> threshold 52, %s utility 52:%n", target);
        boolean blindU = false;
        for (int k = 0; k < m; k++) {
            Map<String, Double> got = mine(k, ux, 52.0);
            boolean has = got.containsKey(target);
            System.out.printf("  %-21s returns it: %s%n", NAMES[k], has ? "yes" : "no");
            if (MEASURED[k] && !has) bad++;
            if (NAMES[k].equals("USpan-as-published") && has) blindU = true;
        }
        if (blindU) { System.out.println("  the published USpan bound does not miss the pattern: the check is blind"); bad++; }
        System.out.println("RESULT " + (bad == 0 ? "every measured baseline matches the enumeration on every comparison"
                : "MISMATCH"));
        System.exit(bad > 0 ? 1 : 0);
    }
}
