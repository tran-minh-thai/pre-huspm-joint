package algorithms;

import common.*;

import java.io.BufferedWriter;
import java.io.FileWriter;
import java.io.IOException;
import java.util.*;

/**
 * Baseline: IncUSP-Miner+ (Wang and Huang, "On Incremental High Utility Sequential Pattern
 * Mining", ACM TIST 9(5), Article 55, 2018). Insertions only, as in the paper.
 *
 * ---------------------------------------------------------------------------
 * PROVENANCE
 *
 * Independent reimplementation from the definitions, lemmas, Theorems 3 and 4, Strategies 1
 * to 6 and Algorithms 1 and 2 of Wang and Huang. No code of the authors or of the SPMF
 * library is used.
 * ---------------------------------------------------------------------------
 *
 * References below are to that paper.
 * - Positions are flat indices of a sequence (Sequence.buildFlatRepresentation); within an
 *   itemset items are sorted, so an I-extension takes a later position of the same itemset.
 * - Each tree node keeps, for every sequence s containing its pattern t, the pairs
 *   (p, u(t,p,s)) ordered by p (Definition 12, Section 4.2.2), and u(t,s), PEU(t,s), TSU(t,s).
 *   Utilities of extensions follow Theorems 3 and 4; u(t,s) follows Lemma 4.
 * - PEU follows Definition 14; TSU follows Definitions 15 and 16.
 * - The candidate pattern tree holds every high-TSU sequence (TSU_D(t) >= min_util) reached by
 *   USP-Miner (Algorithm 1), and each node keeps LM_TSU(t), the largest TSU among t's low-TSU
 *   extension sequences.
 * - The incremental phase is Algorithm 2 with HandleCase-1 and HandleCase-2, using
 *   Strategies 1 to 6.
 *
 * min_util is the threshold ratio times the total utility of the current database, so it is
 * recomputed after every batch. Insertions only raise it, which keeps every tree node built
 * under an earlier, lower threshold a valid (larger) candidate set.
 *
 * Counters: candidateCount counts the distinct extension items generated by every scan of a
 * projected database, before the TSU filter; prunedTSU counts extensions discarded as low TSU;
 * exploredNodes counts calls of USP-Miner and of IncUSP-Miner+.
 */
public class IncUSPMinerPlusAlgorithm {

    public double Su;
    public double currentMinUtil;

    // ========================================================================
    // MEASUREMENT COUNTERS
    // ========================================================================
    public int patternCount = 0;
    public long candidateCount = 0;
    public long exploredNodes = 0;
    public long prunedTSU = 0;
    // Path counters, cumulative over the run, for verification: how often the incremental phase
    // rescanned NDB (Strategy 6), built a new node (HandleCase-2) and re-ran USP-Miner on a node.
    public long ndbScans = 0, case2Builds = 0, rebuilds = 0;

    public Map<Pattern, Double> largeMap = new HashMap<>();

    public IncUSPMinerPlusAlgorithm(double Su) {
        this.Su = Su;
    }

    // ========================================================================
    // DATA STRUCTURES
    // ========================================================================

    /** Utility information of a pattern t in one sequence s. */
    static final class Entry {
        final Sequence seq;
        int[] pos;        // extension positions of t in s, ascending
        double[] util;    // u(t, pos[j], s)
        int size;
        double u;         // u(t, s)       (Lemma 4)
        double peu;       // PEU(t, s)     (Definition 14)
        double tsu;       // TSU(t, s)     (Definitions 15 and 16)

        Entry(Sequence seq) {
            this.seq = seq;
            this.pos = new int[4];
            this.util = new double[4];
        }

        void add(int p, double up) {
            if (size == pos.length) {
                pos = Arrays.copyOf(pos, size * 2);
                util = Arrays.copyOf(util, size * 2);
            }
            pos[size] = p;
            util[size] = up;
            size++;
        }

        /** Computes u(t,s), PEU(t,s) and TSU(t,s); parent is null for a 1-sequence. */
        void finish(Entry parent) {
            pos = Arrays.copyOf(pos, size);
            util = Arrays.copyOf(util, size);
            double[] ru = seq.flatRemainingUtility;
            double best = 0, bestPeu = 0;
            for (int j = 0; j < size; j++) {
                if (util[j] > best) best = util[j];
                double r = ru[pos[j]];
                double pe = r > 0 ? util[j] + r : 0;     // Definition 14
                if (pe > bestPeu) bestPeu = pe;
            }
            u = best;
            peu = bestPeu;
            int p1 = pos[0];
            double ip1 = seq.flatUtilities[p1];
            if (parent == null) {
                tsu = ip1 + ru[p1];                         // Definition 15
            } else if (parent.u == parent.util[0]) {
                tsu = parent.util[0] + ip1 + ru[p1];        // Definition 16, u(a,s) = u(a,ap1,s)
            } else {
                tsu = parent.peu;                           // Definition 16, otherwise
            }
        }
    }

    static final class Node {
        final Pattern pattern;
        final Map<Integer, Entry> entries = new HashMap<>();   // sequence id -> Entry
        double uD, peuD, tsuD;
        double lmTsu = 0;             // LM_TSU(t)
        boolean expanded = false;     // USP-Miner built t's children
        boolean stale = false;        // descendants not updated (Algorithm 2, line 4)
        final Map<Integer, Node> iChildren = new HashMap<>();
        final Map<Integer, Node> sChildren = new HashMap<>();

        Node(Pattern p) { this.pattern = p; }

        void addEntry(Entry e) {
            Entry old = entries.put(e.seq.id, e);
            if (old != null) { uD -= old.u; peuD -= old.peu; tsuD -= old.tsu; }
            uD += e.u; peuD += e.peu; tsuD += e.tsu;
        }
    }

    /** An extension sequence collected by one scan: its entries and the sum of their TSU. */
    static final class Cand {
        final List<Entry> entries = new ArrayList<>();
        double tsu;
    }

    private Node root;
    private final Map<Integer, Sequence> db = new HashMap<>();
    private Set<Integer> ldbIds = Collections.emptySet();

    public void releaseState() {
        root = null;
        db.clear();
        largeMap.clear();
    }

    // ========================================================================
    // INITIAL PHASE
    // ========================================================================
    public void runInitialMining(List<Sequence> dInit, double currentTotalUtility) {
        resetCounters();
        largeMap.clear();
        db.clear();
        currentMinUtil = currentTotalUtility * Su;
        for (Sequence s : dInit) { prepare(s); db.put(s.id, s); }
        ldbIds = Collections.emptySet();
        root = new Node(new Pattern());
        uspMiner(root);
        collectHusps();
    }

    // ========================================================================
    // INCREMENTAL PHASE
    // ========================================================================
    public void runIncrementalMining(List<Sequence> deltaD, List<Sequence> dSoFar, double newTotalUtility) {
        resetCounters();
        largeMap.clear();
        currentMinUtil = newTotalUtility * Su;
        Set<Integer> ldb = new HashSet<>();
        for (Sequence s : deltaD) {
            prepare(s);
            if (db.containsKey(s.id)) throw new IllegalArgumentException(
                    "sequence " + s.id + " is already in the database; IncUSP-Miner+ supports insertions only");
            db.put(s.id, s);
            ldb.add(s.id);
        }
        ldbIds = ldb;
        List<Entry> ldbRoot = new ArrayList<>(deltaD.size());
        for (Sequence s : deltaD) ldbRoot.add(new Entry(s));   // the root has no positions
        incUspMiner(root, ldbRoot);
        ldbIds = Collections.emptySet();
        collectHusps();
    }

    private void resetCounters() {
        patternCount = 0;
        candidateCount = 0;
        exploredNodes = 0;
        prunedTSU = 0;
    }

    private static void prepare(Sequence s) {
        if (s.flatItems == null) {
            s.calculateRemainingUtilities();
            s.buildFlatRepresentation();
        }
    }

    // ========================================================================
    // ALGORITHM 1: USP-Miner(t) on the current database
    // ========================================================================
    private void uspMiner(Node t) {
        if (Thread.currentThread().isInterrupted()) return;
        exploredNodes++;
        t.iChildren.clear();
        t.sChildren.clear();
        t.lmTsu = 0;
        t.stale = false;
        if (t != root && t.peuD < currentMinUtil) {          // line 1
            t.expanded = false;
            return;
        }
        t.expanded = true;
        List<Entry> projected = (t == root) ? rootEntries(db.values()) : new ArrayList<>(t.entries.values());
        Map<Integer, Cand> iList = new HashMap<>(), sList = new HashMap<>();
        scan(t, projected, iList, sList);                     // line 3
        candidateCount += iList.size() + sList.size();
        List<Node> kept = new ArrayList<>();
        keepHighTsu(t, iList, true, kept);                    // line 4: drop low-TSU items
        keepHighTsu(t, sList, false, kept);
        for (Node c : kept) uspMiner(c);                      // lines 5-16
    }

    /** Builds a node for every high-TSU candidate; low-TSU ones only raise LM_TSU(t). */
    private void keepHighTsu(Node t, Map<Integer, Cand> cands, boolean iExt, List<Node> kept) {
        List<Integer> items = new ArrayList<>(cands.keySet());
        Collections.sort(items);
        for (int item : items) {
            Cand c = cands.get(item);
            if (c.tsu < currentMinUtil) {
                prunedTSU++;
                if (c.tsu > t.lmTsu) t.lmTsu = c.tsu;
                continue;
            }
            Node child = newChild(t, item, iExt);
            for (Entry e : c.entries) child.addEntry(e);
            kept.add(child);
        }
    }

    private Node newChild(Node t, int item, boolean iExt) {
        Pattern p = (t == root) ? new Pattern(item)
                : (iExt ? t.pattern.iConcatenate(item) : t.pattern.sConcatenate(item));
        Node child = new Node(p);
        (iExt ? t.iChildren : t.sChildren).put(item, child);
        return child;
    }

    // ========================================================================
    // ALGORITHM 2: IncUSP-Miner+(t)
    // ========================================================================
    /** ldbT: the entries of t in the inserted sequences (for the root, one empty entry each). */
    private void incUspMiner(Node t, List<Entry> ldbT) {
        if (Thread.currentThread().isInterrupted()) return;
        exploredNodes++;
        if (ldbT.isEmpty()) return;                                           // lines 1-3, Strategy 1
        double peuLdb = 0;
        if (t == root) {
            for (Entry e : ldbT) peuLdb += e.seq.sequenceUtility;            // PEU(<>, s) = u(s)
        } else {
            for (Entry e : ldbT) peuLdb += e.peu;
            if (t.peuD < currentMinUtil) {                                    // lines 4-5
                t.stale = true;
                return;
            }
            double peuOld = t.peuD - peuLdb;
            if (!t.expanded || t.stale || peuOld < currentMinUtil) {          // lines 6-8
                rebuilds++;
                uspMiner(t);
                return;
            }
        }

        double emltsu = 0;                                                    // line 9
        Map<Integer, Cand> iLdb = new HashMap<>(), sLdb = new HashMap<>();
        scan(t, ldbT, iLdb, sLdb);                                            // line 10
        candidateCount += iLdb.size() + sLdb.size();

        if (t.lmTsu == 0 || peuLdb + t.lmTsu < currentMinUtil) {             // line 11, Strategies 2 and 3
            emltsu = Math.max(emltsu, handleLdbOnly(t, iLdb, true));          // lines 12-19
            emltsu = Math.max(emltsu, handleLdbOnly(t, sLdb, false));
            t.lmTsu = t.lmTsu + emltsu;                                       // line 34, Strategies 4 and 5
        } else {                                                              // lines 20-33, Strategy 6
            t.lmTsu = 0;                                                      // line 21
            ndbScans++;
            List<Entry> ndbT = new ArrayList<>();
            if (t == root) {
                for (Sequence s : db.values()) if (!ldbIds.contains(s.id)) ndbT.add(new Entry(s));
            } else {
                for (Entry e : t.entries.values()) if (!ldbIds.contains(e.seq.id)) ndbT.add(e);
            }
            Map<Integer, Cand> iNdb = new HashMap<>(), sNdb = new HashMap<>();
            scan(t, ndbT, iNdb, sNdb);                                        // lines 22-23
            candidateCount += iNdb.size() + sNdb.size();
            emltsu = Math.max(emltsu, handleWhole(t, iLdb, iNdb, true));      // lines 24-33
            emltsu = Math.max(emltsu, handleWhole(t, sLdb, sNdb, false));
            t.lmTsu = emltsu;                                                 // line 34
        }
    }

    /** Lines 12-19: only the extensions present in LDB are processed. Returns emltsu. */
    private double handleLdbOnly(Node t, Map<Integer, Cand> ldb, boolean iExt) {
        double emltsu = 0;
        Map<Integer, Node> children = iExt ? t.iChildren : t.sChildren;
        List<Integer> items = new ArrayList<>(ldb.keySet());
        Collections.sort(items);
        for (int item : items) {
            Cand c = ldb.get(item);
            Node child = children.get(item);
            if (child != null) {                                              // case (1)
                handleCase1(child, c.entries);
            } else if (c.tsu >= currentMinUtil) {                             // case (2)
                handleCase2(t, item, iExt, c.entries);
            } else {
                prunedTSU++;
                if (c.tsu > emltsu) emltsu = c.tsu;
            }
        }
        return emltsu;
    }

    /** Lines 24-33: every extension in D' is considered. Returns emltsu. */
    private double handleWhole(Node t, Map<Integer, Cand> ldb, Map<Integer, Cand> ndb, boolean iExt) {
        double emltsu = 0;
        Map<Integer, Node> children = iExt ? t.iChildren : t.sChildren;
        Set<Integer> all = new TreeSet<>(ldb.keySet());
        all.addAll(ndb.keySet());
        for (int item : all) {
            Cand cl = ldb.get(item), cn = ndb.get(item);
            double tsu = (cl == null ? 0 : cl.tsu) + (cn == null ? 0 : cn.tsu);
            Node child = children.get(item);
            // A node already in the tree is always brought up to date. In the paper min_util is
            // fixed, so a tree node stays high TSU after insertions; here min_util rises with the
            // database, a tree node can fall below it, and skipping its update would lose this
            // batch's utility for every later batch.
            if (child != null) {                                              // case (1)
                if (cl != null) handleCase1(child, cl.entries);
                if (tsu < currentMinUtil && tsu > emltsu) emltsu = tsu;
            } else if (tsu >= currentMinUtil) {                               // line 25
                // case (2). Without an instance in LDB, t' was high TSU in D and should already be
                // in T; it is built from its entries in D' all the same rather than skipped.
                List<Entry> whole = new ArrayList<>();
                if (cl != null) whole.addAll(cl.entries);
                if (cn != null) whole.addAll(cn.entries);
                handleCase2(t, item, iExt, whole);
            } else {
                prunedTSU++;
                if (tsu > emltsu) emltsu = tsu;                               // lines 31-33
            }
        }
        return emltsu;
    }

    /** HandleCase-1: update the node with the inserted sequences, then recurse. */
    private void handleCase1(Node child, List<Entry> ldbEntries) {
        for (Entry e : ldbEntries) child.addEntry(e);                         // UpdateNode, Equation (16)
        incUspMiner(child, ldbEntries);
    }

    /** HandleCase-2: build the node from its entries in D', then run USP-Miner on it. */
    private void handleCase2(Node t, int item, boolean iExt, List<Entry> entries) {
        case2Builds++;
        Node child = newChild(t, item, iExt);
        for (Entry e : entries) child.addEntry(e);
        uspMiner(child);
    }

    // ========================================================================
    // PROJECTED-DATABASE SCAN (Theorems 3 and 4)
    // ========================================================================
    /**
     * For each entry of t, collects the I- and S-extension sequences of t with their
     * (p, u(t',p,s)) pairs. Root entries have no positions: their extensions are the
     * 1-sequences, with u(<i>, p, s) = u(i, p, s).
     */
    private void scan(Node t, List<Entry> entries, Map<Integer, Cand> iOut, Map<Integer, Cand> sOut) {
        boolean isRoot = (t == root);
        Map<Integer, Entry> iCur = new HashMap<>(), sCur = new HashMap<>();
        for (Entry pe : entries) {
            Sequence s = pe.seq;
            int[] items = s.flatItems;
            double[] us = s.flatUtilities;
            boolean[] end = s.isItemsetEnd;
            int n = s.flatLen;
            iCur.clear();
            sCur.clear();
            if (isRoot) {
                for (int q = 0; q < n; q++) {
                    Entry ce = sCur.computeIfAbsent(items[q], k -> new Entry(s));
                    ce.add(q, us[q]);
                }
            } else {
                // I-extensions (Theorem 3): u(t',q,s) = u(t,p,s) + u(i',q,s), q after p in p's itemset.
                for (int j = 0; j < pe.size; j++) {
                    int p = pe.pos[j];
                    if (end[p]) continue;
                    for (int q = p + 1; q < n; q++) {
                        Entry ce = iCur.computeIfAbsent(items[q], k -> new Entry(s));
                        ce.add(q, pe.util[j] + us[q]);
                        if (end[q]) break;
                    }
                }
                // S-extensions (Theorem 4): u(t',q,s) = max{u(t,p,s) : p in an earlier itemset} + u(i',q,s).
                int j = 0;
                double best = Double.NEGATIVE_INFINITY;
                for (int q = 0; q < n; q++) {
                    if (q == 0 || end[q - 1]) {                    // q starts a new itemset
                        while (j < pe.size && pe.pos[j] < q) {
                            if (pe.util[j] > best) best = pe.util[j];
                            j++;
                        }
                    }
                    if (best == Double.NEGATIVE_INFINITY) continue;
                    Entry ce = sCur.computeIfAbsent(items[q], k -> new Entry(s));
                    ce.add(q, best + us[q]);
                }
            }
            Entry parent = isRoot ? null : pe;
            flush(iCur, iOut, parent);
            flush(sCur, sOut, parent);
        }
    }

    private static void flush(Map<Integer, Entry> cur, Map<Integer, Cand> out, Entry parent) {
        for (Map.Entry<Integer, Entry> me : cur.entrySet()) {
            Entry e = me.getValue();
            e.finish(parent);
            Cand c = out.computeIfAbsent(me.getKey(), k -> new Cand());
            c.entries.add(e);
            c.tsu += e.tsu;
        }
    }

    private static List<Entry> rootEntries(Collection<Sequence> seqs) {
        List<Entry> out = new ArrayList<>(seqs.size());
        for (Sequence s : seqs) out.add(new Entry(s));
        return out;
    }

    // ========================================================================
    // HUSP SET
    // ========================================================================
    private void collectHusps() {
        largeMap.clear();
        if (root != null) {
            Deque<Node> stack = new ArrayDeque<>();
            stack.push(root);
            while (!stack.isEmpty()) {
                Node n = stack.pop();
                if (n != root && n.uD >= currentMinUtil) largeMap.put(n.pattern, n.uD);
                if (n.stale) continue;      // descendants hold no HUSP: u <= PEU(t) < min_util
                for (Node c : n.iChildren.values()) stack.push(c);
                for (Node c : n.sChildren.values()) stack.push(c);
            }
        }
        patternCount = largeMap.size();
    }

    /** The HUSPs with their utilities, for verification. */
    public Map<Pattern, Double> husps() { return Collections.unmodifiableMap(largeMap); }

    public void exportLargePatterns(String outputPath) {
        if (outputPath == null) return;
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(outputPath))) {
            List<Map.Entry<Pattern, Double>> sortedEntries = new ArrayList<>(largeMap.entrySet());
            sortedEntries.sort((e1, e2) -> Double.compare(e2.getValue(), e1.getValue()));
            for (Map.Entry<Pattern, Double> entry : sortedEntries) {
                writer.write(entry.getKey().toIntuitiveString() + " #UTIL: " + entry.getValue());
                writer.newLine();
            }
        } catch (IOException e) {
            System.err.println("Error writing IncUSP-MinerPlus output file: " + e.getMessage());
        }
    }
}
